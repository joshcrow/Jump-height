#!/usr/bin/env python3
"""E7 — threshold sensitivity sweep against REAL recorded motion.

WHY THIS IS DIFFERENT FROM E1-E6
--------------------------------
Every prior experiment in this directory ran against synthetic data from
`sim/generate.py`. Synthetic data is generated by the same physical model the
detector assumes, so it can tell us the detector is self-consistent, and it
cannot tell us how the detector behaves on motion a person actually made.

On 2026-08-15 the project got its first large real recording: 638,852 samples
(~3.5 h) of a puck carried around in a pocket all evening, with some deliberate
tosses in it. This sweeps the detector's four decision gates across that
recording and asks the question that matters before a one-shot water session:

    Are we standing on a plateau, or on a cliff edge?

If a 10 % change in a threshold flips the number of jumps found, then real
water motion — which will differ from a pocket and a hand toss — could easily
land on the wrong side of it, and we would never know from the beach.

THE GROUND TRUTH, AND WHY IT IS NOT CIRCULAR
--------------------------------------------
The device found 10 events in this recording. Nine have a median airborne |a|
between 0.039 g and 0.154 g. One — event 7 — sits at 1.393 g.

An object in free fall reads ~0 g **by definition**. 1.393 g is not a jump that
was measured badly; it is not a jump. That single physical criterion separates
the set with a 10x gap and no tuning, and it is independent of the detection
gates being swept (it looks at what the acceleration DID during the window, not
at the thresholds that opened the window).

So: nine "should keep", one "should reject". A parameter set that keeps all
nine and drops the 1.393 g event is strictly better than one that does not.

WHAT IT PRODUCES
----------------
One CSV row per parameter combination:
  * how many events it finds,
  * how many of the nine known-good it keeps,
  * how many high-|a| (non-free-fall) events it lets through,
  * and any NEW low-|a| events the shipped settings currently miss.

That last column is the interesting one. A more sensitive setting that surfaces
extra events with free-fall-consistent physics is not noise — it is a jump the
current configuration is throwing away.

Usage:
    python3 sim/experiments/e7_threshold_sweep.py --out sim/experiments/out/e7.csv
    python3 sim/experiments/e7_threshold_sweep.py --quick     # tiny grid, smoke test
"""

from __future__ import annotations

import argparse
import bisect
import csv
import itertools
import os
import sys
import time
from dataclasses import replace
from multiprocessing import Pool, cpu_count
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO / "sim"))

from detector import Detector, load_params  # noqa: E402

TRACE = (REPO / "data" / "sessions" / "walk-overnight" / "pull-a" /
         "20260815-115418" / "trace.csv")

# The nine events whose airborne physics is consistent with free fall, from the
# device's own flight-physics columns (jumps.csv, med_acorr_g). Times are the
# device's takeoff_s. Event 7 (t=4650.087, med_a=1.393 g) is deliberately absent.
KNOWN_GOOD_S = [746.196, 748.622, 751.747, 753.837, 755.852,
                4427.912, 16150.687, 16164.731, 16167.106]
KNOWN_BAD_S = [4650.087]

MATCH_S = 1.0          # same tolerance sim/evaluate.py uses to call it "the same jump"
FREEFALL_MAX_G = 0.35  # above this median |a|, the window was not free fall (E5's gate)

_TRACE_CACHE: list[tuple[float, float]] = []
_TIMES_CACHE: list[float] = []
_MAGS_CACHE: list[float] = []


def load_trace(path: Path) -> list[tuple[float, float]]:
    rows = []
    with open(path) as f:
        r = csv.reader(f)
        next(r, None)                       # header: t,mag
        for parts in r:
            if len(parts) >= 2:
                try:
                    rows.append((float(parts[0]), float(parts[1])))
                except ValueError:
                    continue
    return rows


def _median(xs):
    if not xs:
        return None
    s = sorted(xs)
    n = len(s)
    return s[n // 2] if n % 2 else 0.5 * (s[n // 2 - 1] + s[n // 2])


def _init():
    """Per-worker setup: parse the trace once, not once per combination."""
    global _TRACE_CACHE, _TIMES_CACHE, _MAGS_CACHE
    _TRACE_CACHE = load_trace(TRACE)
    _TIMES_CACHE = [t for t, _ in _TRACE_CACHE]
    _MAGS_CACHE = [m for _, m in _TRACE_CACHE]


def run_combo(combo: dict) -> dict:
    """Replay the whole real trace once under one parameter set."""
    trace = _TRACE_CACHE
    p = replace(load_params(), **combo)
    det = Detector(p)

    events = []
    for t, mag in trace:
        ev = det.update(t, mag)
        if ev is not None:
            events.append(ev)

    # Classify each detection by what the acceleration actually did during the
    # window it claims was flight. This is the independent physical check.
    #
    # The trace is time-ordered, so bisect the window instead of rescanning all
    # 638k rows per event — that inner scan dominated the runtime otherwise.
    times = _TIMES_CACHE
    mags = _MAGS_CACHE
    classified = []
    for ev in events:
        t0 = ev.takeoff_time_s
        t1 = t0 + ev.airtime_raw_s
        lo = bisect.bisect_left(times, t0)
        hi = bisect.bisect_right(times, t1)
        med = _median(mags[lo:hi])
        classified.append((t0, med if med is not None else float("nan")))

    kept_good = sum(1 for g in KNOWN_GOOD_S
                    if any(abs(t0 - g) <= MATCH_S for t0, _ in classified))
    kept_bad = sum(1 for b in KNOWN_BAD_S
                   if any(abs(t0 - b) <= MATCH_S for t0, _ in classified))

    known = KNOWN_GOOD_S + KNOWN_BAD_S
    novel = [(t0, med) for t0, med in classified
             if not any(abs(t0 - k) <= MATCH_S for k in known)]
    novel_freefall = sum(1 for _, med in novel if med == med and med < FREEFALL_MAX_G)
    novel_junk = len(novel) - novel_freefall

    high_a = sum(1 for _, med in classified if med == med and med >= FREEFALL_MAX_G)

    out = dict(combo)
    out.update({
        "n_events": len(events),
        "kept_good": kept_good,
        "missed_good": len(KNOWN_GOOD_S) - kept_good,
        "kept_known_bad": kept_bad,
        "high_a_events": high_a,
        "novel_freefall": novel_freefall,
        "novel_junk": novel_junk,
        "times": ";".join(f"{t0:.2f}" for t0, _ in classified[:40]),
    })
    return out


def build_grid(quick: bool) -> list[dict]:
    if quick:
        grid = {
            "freefall_enter_g": [0.30, 0.35, 0.40],
            "min_airtime_s": [0.25, 0.35],
        }
    else:
        grid = {
            # The gate that decides "this might be a takeoff". The whole
            # detection chain hangs off it.
            "freefall_enter_g": [0.15, 0.18, 0.20, 0.22, 0.25, 0.28, 0.30,
                                 0.32, 0.34, 0.35, 0.36, 0.38, 0.40, 0.42,
                                 0.45, 0.50, 0.55, 0.60],
            # How long |a| must stay low before we believe it.
            "freefall_confirm_s": [0.02, 0.04, 0.06, 0.08, 0.10, 0.12, 0.16],
            # The impact that ends a flight.
            "landing_threshold_g": [1.50, 1.80, 2.20, 2.50, 2.80, 3.00, 3.50],
            # The shortest thing we are willing to call a jump. Event 7 (the
            # known false positive) had a 0.30 s airtime, so this one is
            # directly implicated in whether it survives.
            "min_airtime_s": [0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50],
        }
    keys = list(grid)
    return [dict(zip(keys, vals)) for vals in itertools.product(*grid.values())]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(REPO / "sim" / "experiments" / "out" / "e7_sweep.csv"))
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--jobs", type=int, default=max(1, cpu_count() - 2))
    args = ap.parse_args()

    if not TRACE.exists():
        print(f"trace not found: {TRACE}", file=sys.stderr)
        return 1

    combos = build_grid(args.quick)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    print(f"E7 threshold sweep")
    print(f"  trace   : {TRACE.relative_to(REPO)}")
    print(f"  combos  : {len(combos)}")
    print(f"  jobs    : {args.jobs}")
    print(f"  out     : {out}")

    t0 = time.time()
    rows = []
    with Pool(args.jobs, initializer=_init) as pool:
        for i, row in enumerate(pool.imap_unordered(run_combo, combos, chunksize=1), 1):
            rows.append(row)
            if i % 25 == 0 or i == len(combos):
                el = time.time() - t0
                rate = i / el if el else 0
                eta = (len(combos) - i) / rate if rate else 0
                print(f"  {i}/{len(combos)}  {el/60:.1f} min elapsed, "
                      f"~{eta/60:.1f} min left", flush=True)

    if rows:
        keys = [k for k in rows[0] if k != "times"] + ["times"]
        with open(out, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=keys)
            w.writeheader()
            for r in rows:
                w.writerow(r)

    # A perfect run keeps all nine and rejects the one that is not free fall.
    perfect = [r for r in rows
               if r["kept_good"] == len(KNOWN_GOOD_S)
               and r["kept_known_bad"] == 0 and r["novel_junk"] == 0]
    print(f"\ndone in {(time.time()-t0)/60:.1f} min — {len(rows)} combos")
    print(f"  keep all {len(KNOWN_GOOD_S)} good AND reject the 1.393 g event: "
          f"{len(perfect)} combos")
    return 0


if __name__ == "__main__":
    sys.exit(main())
